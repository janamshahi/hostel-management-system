# ==========================================================
# STUDENT ID GENERATOR
# ==========================================================

def generate_student_id():
    """
    Generate the next available Student ID.

    Format:

        DBH-001
        DBH-002
        DBH-003
        DBH-004

    Existing Student IDs are checked so that the generated
    ID is not duplicated.
    """

    existing_ids = Student.objects.values_list(
        'student_id',
        flat=True
    )

    used_numbers = []

    for student_id in existing_ids:

        if not student_id:
            continue

        student_id = student_id.strip()

        if student_id.upper().startswith('DBH-'):

            number_part = student_id[4:]

            if number_part.isdigit():

                used_numbers.append(
                    int(number_part)
                )

    next_number = 1

    while next_number in used_numbers:

        next_number += 1

    return f'DBH-{next_number:03d}'


# ==========================================================
# STUDENT REGISTRATION
# ==========================================================

def register_view(request):
    """
    Register a new hostel student.

    Student ID is automatically generated by the system.

    Example:

        DBH-001
        DBH-002
        DBH-003

    Students cannot manually change the generated ID.
    """

    # ------------------------------------------------------
    # ALREADY LOGGED-IN USER
    # ------------------------------------------------------

    if request.user.is_authenticated:

        if request.user.is_superuser:

            return redirect(
                'admin_dashboard'
            )

        return redirect(
            'student_dashboard'
        )

    # ------------------------------------------------------
    # GENERATE STUDENT ID FOR REGISTRATION PAGE
    # ------------------------------------------------------

    generated_student_id = generate_student_id()

    # ------------------------------------------------------
    # HANDLE REGISTRATION FORM
    # ------------------------------------------------------

    if request.method == 'POST':

        # ==================================================
        # ACCOUNT INFORMATION
        # ==================================================

        username = request.POST.get(
            'username',
            ''
        ).strip()

        password = request.POST.get(
            'password',
            ''
        )

        # ==================================================
        # PERSONAL INFORMATION
        # ==================================================

        full_name = request.POST.get(
            'full_name',
            ''
        ).strip()

        email = request.POST.get(
            'email',
            ''
        ).strip()

        phone = request.POST.get(
            'phone',
            ''
        ).strip()

        address = request.POST.get(
            'address',
            ''
        ).strip()

        # ==================================================
        # GUARDIAN INFORMATION
        # ==================================================

        guardian_name = request.POST.get(
            'guardian_name',
            ''
        ).strip()

        guardian_phone = request.POST.get(
            'guardian_phone',
            ''
        ).strip()

        # ==================================================
        # ALWAYS GENERATE STUDENT ID FROM SERVER
        # ==================================================

        student_id = generate_student_id()

        # ==================================================
        # REQUIRED FIELD VALIDATION
        # ==================================================

        if not username or not password:

            messages.error(
                request,
                'Username and password are required.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        if not full_name:

            messages.error(
                request,
                'Full name is required.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        if not email:

            messages.error(
                request,
                'Email address is required.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        if not phone:

            messages.error(
                request,
                'Phone number is required.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        if not address:

            messages.error(
                request,
                'Address is required.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        if not guardian_name:

            messages.error(
                request,
                'Guardian name is required.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        if not guardian_phone:

            messages.error(
                request,
                'Guardian phone number is required.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        # ==================================================
        # USERNAME VALIDATION
        # ==================================================

        if User.objects.filter(
            username=username
        ).exists():

            messages.error(
                request,
                'Username already exists. Please choose another username.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        # ==================================================
        # STUDENT ID VALIDATION
        # ==================================================

        if Student.objects.filter(
            student_id=student_id
        ).exists():

            student_id = generate_student_id()

            messages.warning(
                request,
                f'A new Student ID has been generated: {student_id}'
            )

        # ==================================================
        # EMAIL VALIDATION
        # ==================================================

        if User.objects.filter(
            email__iexact=email
        ).exists():

            messages.error(
                request,
                'This email address is already registered.'
            )

            return render(
                request,
                'accounts/register.html',
                {
                    'generated_student_id': student_id
                }
            )

        # ==================================================
        # CREATE DJANGO USER
        # ==================================================

        user = User.objects.create_user(
            username=username,
            email=email,
            password=password,
            first_name=full_name
        )

        # ==================================================
        # CREATE STUDENT PROFILE
        # ==================================================

        Student.objects.create(
            user=user,
            student_id=student_id,
            full_name=full_name,
            phone=phone,
            email=email,
            address=address,
            guardian_name=guardian_name,
            guardian_phone=guardian_phone,
            gender='Female'
        )

        # ==================================================
        # REGISTRATION SUCCESS MESSAGE
        # ==================================================

        messages.success(
            request,
            f'Registration successful. Your Student ID is {student_id}. Please login.'
        )

        # ==================================================
        # REDIRECT TO STUDENT LOGIN
        # ==================================================

        return redirect(
            'login'
        )

    # ======================================================
    # DISPLAY REGISTRATION PAGE
    # ======================================================

    return render(
        request,
        'accounts/register.html',
        {
            'generated_student_id': generated_student_id
        }
    )


