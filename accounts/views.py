def login_view(request):
    """
    Login page for normal hostel students.

    IMPORTANT ACCESS RULES:

    1. Normal student credentials:
       Login successfully and go to student dashboard.

    2. Administrator credentials:
       Completely blocked from this page.
       The administrator is NOT logged in.
       The administrator is NOT redirected to /admin/.
       The administrator remains on the student login page.

    3. Invalid credentials:
       Remain on the student login page.
    """

    # ------------------------------------------------------
    # ALREADY LOGGED-IN USER
    # ------------------------------------------------------

    if request.user.is_authenticated:

        # --------------------------------------------------
        # ADMINISTRATOR ALREADY LOGGED IN
        # --------------------------------------------------

        if request.user.is_superuser:

            return redirect(
                'admin_dashboard'
            )

        # --------------------------------------------------
        # NORMAL STUDENT ALREADY LOGGED IN
        # --------------------------------------------------

        return redirect(
            'student_dashboard'
        )

    # ------------------------------------------------------
    # HANDLE LOGIN FORM
    # ------------------------------------------------------

    if request.method == 'POST':

        username = request.POST.get(
            'username',
            ''
        ).strip()

        password = request.POST.get(
            'password',
            ''
        )

        # ==================================================
        # EMPTY FIELD VALIDATION
        # ==================================================

        if not username or not password:

            messages.error(
                request,
                'Please enter both username and password.'
            )

            return render(
                request,
                'accounts/login.html'
            )

        # ==================================================
        # AUTHENTICATE USER
        # ==================================================

        user = authenticate(
            request,
            username=username,
            password=password
        )

        # ==================================================
        # INVALID LOGIN
        # ==================================================

        if user is None:

            messages.error(
                request,
                'Invalid student username or password.'
            )

            return render(
                request,
                'accounts/login.html'
            )

        # ==================================================
        # BLOCK ADMINISTRATOR FROM STUDENT LOGIN
        # ==================================================

        if user.is_superuser:

            messages.error(
                request,
                'Administrator accounts cannot use the student login page.'
            )

            # IMPORTANT:
            #
            # Do NOT call login().
            #
            # Do NOT redirect to admin_login.
            #
            # Render the same student login page.
            #
            return render(
                request,
                'accounts/login.html'
            )

        # ==================================================
        # CHECK STUDENT PROFILE
        # ==================================================

        if not hasattr(
            user,
            'student_profile'
        ):

            messages.error(
                request,
                'Student profile not found. Please contact the hostel administrator.'
            )

            return render(
                request,
                'accounts/login.html'
            )

        # ==================================================
        # LOGIN STUDENT
        # ==================================================

        login(
            request,
            user
        )

        # ==================================================
        # SUCCESS MESSAGE
        # ==================================================

        messages.success(
            request,
            'Login successful. Welcome to DIDI BAHINI GIRLS HOSTEL.'
        )

        # ==================================================
        # STUDENT DASHBOARD
        # ==================================================

        return redirect(
            'student_dashboard'
        )

    # ======================================================
    # DISPLAY STUDENT LOGIN PAGE
    # ======================================================

    return render(
        request,
        'accounts/login.html'
    )


# ==========================================================
# ADMINISTRATOR LOGIN
# ==========================================================

def admin_login_view(request):
    """
    Custom administrator login page.

    URL:

        /admin/

    Only Django superusers are allowed to login here.

    Successful administrator login redirects to:

        /dashboard/admin/
    """

    # ------------------------------------------------------
    # ALREADY LOGGED-IN USER
    # ------------------------------------------------------

    if request.user.is_authenticated:

        # --------------------------------------------------
        # ADMINISTRATOR
        # --------------------------------------------------

        if request.user.is_superuser:

            return redirect(
                'admin_dashboard'
            )

        # --------------------------------------------------
        # NORMAL STUDENT CANNOT ACCESS ADMIN PORTAL
        # --------------------------------------------------

        messages.warning(
            request,
            'Student accounts cannot access the administrator portal.'
        )

        return redirect(
            'student_dashboard'
        )

    # ------------------------------------------------------
    # HANDLE ADMIN LOGIN FORM
    # ------------------------------------------------------

    if request.method == 'POST':

        username = request.POST.get(
            'username',
            ''
        ).strip()

        password = request.POST.get(
            'password',
            ''
        )

        # ==================================================
        # EMPTY FIELD VALIDATION
        # ==================================================

        if not username or not password:

            messages.error(
                request,
                'Please enter administrator username and password.'
            )

            return render(
                request,
                'accounts/admin_login.html'
            )

        # ==================================================
        # AUTHENTICATE ADMINISTRATOR
        # ==================================================

        user = authenticate(
            request,
            username=username,
            password=password
        )

        # ==================================================
        # INVALID ADMIN LOGIN
        # ==================================================

        if user is None:

            messages.error(
                request,
                'Invalid administrator username or password.'
            )

            return render(
                request,
                'accounts/admin_login.html'
            )

        # ==================================================
        # BLOCK NORMAL STUDENT
        # ==================================================

        if not user.is_superuser:

            messages.error(
                request,
                'Access denied. This account is not an administrator account.'
            )

            return render(
                request,
                'accounts/admin_login.html'
            )

        # ==================================================
        # LOGIN ADMINISTRATOR
        # ==================================================

        login(
            request,
            user
        )

        # ==================================================
        # ADMIN LOGIN SUCCESS MESSAGE
        # ==================================================

        messages.success(
            request,
            'Welcome to the DIDI BAHINI GIRLS HOSTEL Administrator Dashboard.'
        )

        # ==================================================
        # ADMIN DASHBOARD
        # ==================================================

        return redirect(
            'admin_dashboard'
        )

    # ======================================================
    # DISPLAY ADMIN LOGIN PAGE
    # ======================================================

    return render(
        request,
        'accounts/admin_login.html'
    )


# ==========================================================
