def logout_view(request):
    """
    Logout the currently authenticated user.

    After logout, the user is redirected to the public
    Home page.
    """

    # ------------------------------------------------------
    # LOGOUT CURRENT USER
    # ------------------------------------------------------

    logout(
        request
    )

    # ------------------------------------------------------
    # LOGOUT SUCCESS MESSAGE
    # ------------------------------------------------------

    messages.success(
        request,
        'You have been logged out successfully.'
    )

    # ------------------------------------------------------
    # REDIRECT TO HOME
    # ------------------------------------------------------

    return redirect(
        'home'
    )
